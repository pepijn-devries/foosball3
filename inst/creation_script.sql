CREATE VIEW player_combos AS
SELECT PLAYER_1, PLAYER_2, COMBI, TOURNAMENT_ID, TOURNAMENT_PHASE_CODE, COUNT(DISTINCT MATCH_ID) TIMES FROM (
  SELECT * FROM (
    SELECT MATCH_ID, PLAYER_DEFENSE_1 PLAYER_1, PLAYER_DEFENSE_2 PLAYER_2, 'DoD' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_DEFENSE_1 PLAYER_1, PLAYER_STRIKE_2 PLAYER_2, 'DoS' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_DEFENSE_1 PLAYER_1, PLAYER_STRIKE_1 PLAYER_2, 'DwS' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_STRIKE_1 PLAYER_1, PLAYER_DEFENSE_2 PLAYER_2, 'SoD' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_STRIKE_1 PLAYER_1, PLAYER_STRIKE_2 PLAYER_2, 'SoS' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_STRIKE_1 PLAYER_1, PLAYER_DEFENSE_1 PLAYER_2, 'SwD' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_DEFENSE_2 PLAYER_1, PLAYER_DEFENSE_1 PLAYER_2, 'DoD' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_DEFENSE_2 PLAYER_1, PLAYER_STRIKE_1 PLAYER_2, 'DoS' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_DEFENSE_2 PLAYER_1, PLAYER_STRIKE_2 PLAYER_2, 'DwS' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_STRIKE_2 PLAYER_1, PLAYER_DEFENSE_1 PLAYER_2, 'SoD' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_STRIKE_2 PLAYER_1, PLAYER_STRIKE_1 PLAYER_2, 'SoS' COMBI FROM match_positions
    UNION ALL
    SELECT MATCH_ID, PLAYER_STRIKE_2 PLAYER_1, PLAYER_DEFENSE_2 PLAYER_2, 'SwD' COMBI FROM match_positions
  ) LEFT JOIN matches USING(MATCH_ID)
