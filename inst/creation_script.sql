CREATE VIEW match_positions AS
SELECT
       MATCH_ID,
       MIN(IIF(POSITION_CODE IN ('D1', 'U1', 'DU', 'UU'), PARTICIPANT_NAME, NULL)) PLAYER_DEFENSE_1,
       MAX(IIF(POSITION_CODE IN ('S1', 'U1', 'SU', 'UU'), PARTICIPANT_NAME, NULL)) PLAYER_STRIKE_1,
       MIN(IIF(POSITION_CODE IN ('D2', 'U2', 'DO', 'UO'), PARTICIPANT_NAME, NULL)) PLAYER_DEFENSE_2,
       MAX(IIF(POSITION_CODE IN ('S2', 'U2', 'SO', 'UO'), PARTICIPANT_NAME, NULL)) PLAYER_STRIKE_2
FROM match_players
LEFT JOIN (SELECT PARTICIPANT_ID,PARTICIPANT_NAME FROM participants_view) USING (PARTICIPANT_ID)
GROUP BY MATCH_ID;
CREATE VIEW participants_view AS
SELECT TOURNAMENT_ID,
       PARTICIPANT_ID,
       PERSON_NAME AS PARTICIPANT_NAME
FROM(
  SELECT * FROM participants
  LEFT JOIN (SELECT PERSON_ID, PERSON_NAME FROM persons) USING(PERSON_ID)
);
CREATE VIEW matches_view AS
SELECT TOURNAMENT_ID,
       TOURNAMENT_PHASE,
       MATCH_ID,
       PLAYER_DEFENSE_1,
       PLAYER_STRIKE_1,
       PLAYER_DEFENSE_2,
       PLAYER_STRIKE_2,
       MAX(IIF(PSEUDO_SIDE_ID='1', RESULT, NULL)) SCORE_1,
       MAX(IIF(PSEUDO_SIDE_ID='2', RESULT, NULL)) SCORE_2,
       TABLE_NAME,
       COLOR_NAME1,
       COLOR_RGB1,
       COLOR_NAME2,
       COLOR_RGB2
FROM (
  SELECT * FROM matches
  LEFT JOIN match_positions USING (MATCH_ID)
  LEFT JOIN tournament_phases USING(TOURNAMENT_PHASE_CODE)
  LEFT JOIN match_results USING(MATCH_ID)
  LEFT JOIN (SELECT SIDE_ID, PSEUDO_SIDE_ID FROM positions) USING (SIDE_ID)
  LEFT JOIN tables USING(TABLE_CODE)
  LEFT JOIN (SELECT TABLE_CODE,COLOR_NAME AS COLOR_NAME1,COLOR_RGB AS COLOR_RGB1 FROM side_properties WHERE SIDE_ID = '1') USING(TABLE_CODE)
  LEFT JOIN (SELECT TABLE_CODE,COLOR_NAME AS COLOR_NAME2,COLOR_RGB AS COLOR_RGB2 FROM side_properties WHERE SIDE_ID = '2') USING(TABLE_CODE)
)
GROUP BY MATCH_ID;
CREATE VIEW opponent_results AS
SELECT MATCH_ID, SIDE_ID, PSEUDO_SIDE_ID, RESULT, RESULT_OPPONENT,
     CASE SIGN(RESULT - RESULT_OPPONENT)
       WHEN 1 THEN 'WIN'
       WHEN 0 THEN 'DRAW'
       WHEN -1 THEN 'LOSE'
     END CONCLUSION,
     POINT_SYSTEM_ID,
     MAX_POINTS_PER_MATCH
FROM (
  SELECT * FROM(
    SELECT DISTINCT * FROM match_results
    LEFT JOIN (SELECT SIDE_ID, PSEUDO_SIDE_ID FROM positions) USING(SIDE_ID)
  ) AS m_r
  LEFT JOIN (
    SELECT PSEUDO_SIDE_ID, 3 - PSEUDO_SIDE_ID AS OPPOSIT_SIDE, RESULT AS RESULT_OPPONENT, MATCH_ID FROM (
      SELECT DISTINCT * FROM match_results
      LEFT JOIN (SELECT DISTINCT SIDE_ID, PSEUDO_SIDE_ID FROM positions) USING(SIDE_ID)
    ) 
  ) AS oppo ON oppo.OPPOSIT_SIDE=m_r.PSEUDO_SIDE_ID AND oppo.MATCH_ID=m_r.MATCH_ID
)
LEFT JOIN (SELECT TOURNAMENT_ID, MATCH_ID FROM matches) USING(MATCH_ID)
LEFT JOIN (SELECT TOURNAMENT_ID, POINT_SYSTEM_ID FROM tournaments) USING(TOURNAMENT_ID)
LEFT JOIN (SELECT POINT_SYSTEM_ID, MAX_POINTS_PER_MATCH FROM point_systems) USING(POINT_SYSTEM_ID)
ORDER BY MATCH_ID;
CREATE VIEW participant_match_results AS
SELECT DISTINCT
  TOURNAMENT_ID,
  TOURNAMENT_DATE,
  LOCATION_NAME,
  LOCATION_CITY,
  TOURNAMENT_PHASE,
  mp.MATCH_ID,
  PARTICIPANT_ID,
  POSITION_CODE,
  ROLE_CODE,
  mp.SIDE_ID,
  PERSON_ID,
  PERSON_NAME AS PARTICIPANT,
  RESULT,
  RESULT_OPPONENT,
  PENALTY_POINTS,
  CONCLUSION,
  CASE TOURNAMENT_PHASE
    WHEN 'Qualification' THEN (
      CASE POINT_SYSTEM_ID
        WHEN 1 THEN (
          CASE CONCLUSION
            WHEN 'WIN' THEN 3
            WHEN 'DRAW' THEN 1
            ELSE 0
          END
        )
        WHEN 2 THEN RESULT - PENALTY_POINTS
        ELSE NULL
      END
    ) ELSE (
      IIF(CONCLUSION='WIN', 1, 0)
    )
  END MATCH_POINTS,
  (IIF(
    RESULT = 0 AND RESULT_OPPONENT = 0,
    0.5,
    CAST(RESULT AS FLOAT)/CAST((RESULT + RESULT_OPPONENT) AS FLOAT)
  )) AS SUCCESS_RATE
FROM (
  SELECT
    MATCH_ID,
    PARTICIPANT_ID,
    POSITION_CODE,
    ROLE_CODE,
    SIDE_ID,
    TOURNAMENT_PHASE_CODE
  FROM participants
  LEFT JOIN (
    SELECT DISTINCT
      MATCH_ID,
      PARTICIPANT_ID,
      POSITION_CODE,
      ROLE_CODE,
      SIDE_ID,
      TOURNAMENT_PHASE_CODE
    FROM match_players
    LEFT JOIN positions USING(POSITION_CODE)
    LEFT JOIN (SELECT MATCH_ID, TOURNAMENT_ID, TOURNAMENT_PHASE_CODE FROM matches) USING(MATCH_ID)
  ) USING(PARTICIPANT_ID)
) AS mp
LEFT JOIN (SELECT MATCH_ID, SIDE_ID, RESULT, RESULT_OPPONENT, POINT_SYSTEM_ID, CONCLUSION FROM opponent_results) AS o_r
  ON mp.MATCH_ID = o_r.MATCH_ID AND mp.SIDE_ID = o_r.SIDE_ID
LEFT JOIN participants USING(PARTICIPANT_ID)
LEFT JOIN persons USING(PERSON_ID)
LEFT JOIN tournament_phases USING(TOURNAMENT_PHASE_CODE)
LEFT JOIN (SELECT TOURNAMENT_ID, TOURNAMENT_DATE, LOCATION_CODE FROM tournaments) USING(TOURNAMENT_ID)
LEFT JOIN (SELECT LOCATION_NAME, LOCATION_CODE, LOCATION_CITY FROM locations) USING (LOCATION_CODE);
CREATE VIEW participant_tournament_results AS
SELECT TOURNAMENT_ID, TOURNAMENT_PHASE, TOURNAMENT_DATE, LOCATION_CITY, MAX_POINTS_PER_MATCH, PERSON_ID, PARTICIPANT_ID,
  PARTICIPANT, PARTICIPANT_HOME, PENALTY_POINTS, RESULT, RESULT_OPPONENT, WINS, LOSSES, DRAWS, MATCHES_PLAYED, TOTAL_MATCHES,
  (TOTAL_MATCHES - MATCHES_PLAYED)*MAX_POINTS_PER_MATCH AS REMAINING_POINTS,
  (TOTAL_MATCHES - MATCHES_PLAYED)*MAX_POINTS_PER_MATCH + IIF(TOURNAMENT_POINTS IS NULL, 0, TOURNAMENT_POINTS) AS POTENTIAL_POINTS,
  IIF(TOURNAMENT_POINTS IS NULL, 0, TOURNAMENT_POINTS) AS TOURNAMENT_POINTS,
  RANK () OVER (
		PARTITION BY TOURNAMENT_ID, TOURNAMENT_PHASE
		ORDER BY ((TOTAL_MATCHES - MATCHES_PLAYED)*MAX_POINTS_PER_MATCH + IIF(TOURNAMENT_POINTS IS NULL, 0, TOURNAMENT_POINTS)) DESC
	) POTENTIAL_RANK,
  RANK () OVER (
		PARTITION BY TOURNAMENT_ID, TOURNAMENT_PHASE
		ORDER BY TOURNAMENT_POINTS DESC
	) TOURNAMENT_RANK
FROM (
  SELECT
    TOURNAMENT_ID,
    TOURNAMENT_PHASE,
    TOURNAMENT_DATE,
    LOCATION_CITY,
    MAX_POINTS_PER_MATCH,
    PERSON_ID,
    PARTICIPANT_ID,
    PARTICIPANT,
    PENALTY_POINTS,
    SUM(RESULT) AS RESULT,
    SUM(RESULT_OPPONENT) AS RESULT_OPPONENT,
    SUM(IIF(CONCLUSION = 'WIN', 1, 0)) AS WINS,
    SUM(IIF(CONCLUSION = 'LOSE', 1, 0)) AS LOSSES,
    SUM(IIF(CONCLUSION = 'DRAW', 1, 0)) AS DRAWS,
    CASE POINT_SYSTEM_ID
      WHEN 1 THEN CAST(SUM(MATCH_POINTS) - PENALTY_POINTS AS FLOAT) + 0.9*AVG(SUCCESS_RATE)
      WHEN 2 THEN CAST(SUM(MATCH_POINTS) - PENALTY_POINTS AS FLOAT) + 1.0 - CAST(SUM(RESULT_OPPONENT) AS FLOAT)/(10.0*CAST(COUNT(MATCH_ID) AS FLOAT))
      ELSE NULL
    END TOURNAMENT_POINTS,
    SUM(IIF(RESULT IS NULL OR RESULT_OPPONENT IS NULL, 0, 1)) AS MATCHES_PLAYED,
    COUNT(MATCH_ID) AS TOTAL_MATCHES
  FROM participant_match_results
  LEFT JOIN (SELECT POINT_SYSTEM_ID, TOURNAMENT_ID, LOCATION_CODE FROM tournaments) USING (TOURNAMENT_ID)
  LEFT JOIN (SELECT POINT_SYSTEM_ID, MAX_POINTS_PER_MATCH FROM point_systems) USING(POINT_SYSTEM_ID)
  GROUP BY TOURNAMENT_ID, TOURNAMENT_PHASE, PARTICIPANT_ID
)
LEFT JOIN (
  SELECT * FROM (
    SELECT PERSON_NAME PARTICIPANT, HOME_BASE FROM persons
  ) LEFT JOIN (SELECT LOCATION_CODE HOME_BASE, LOCATION_CITY PARTICIPANT_HOME FROM locations) USING(HOME_BASE)
) USING(PARTICIPANT)
ORDER BY TOURNAMENT_ID, TOURNAMENT_PHASE, TOURNAMENT_RANK;
CREATE VIEW player_statistics AS
SELECT DISTINCT
PERSON_ID,
QUALIFICATION_CODE,
PARTICIPANT,
TOURNAMENT_PHASE,
SUM(RESULT) AS GOALS_SCORED,
SUM(RESULT_OPPONENT) AS GOALS_CONCEDED,
CAST(SUM(RESULT) AS FLOAT)/CAST(SUM(RESULT_OPPONENT) AS FLOAT) AS GOAL_RATIO,
CAST(SUM(RESULT) AS FLOAT)/CAST((SUM(RESULT_OPPONENT) + SUM(RESULT)) AS FLOAT) AS SUCCESS_RATE,
IIF(QUALIFICATION_CODE='H', IIF(RESULT IS NULL, 0.5, CAST(SUM(RESULT) AS FLOAT)/CAST((SUM(RESULT_OPPONENT) + SUM(RESULT)) AS FLOAT)), QUALIFICATION_SUCCESS) AS QUALIFICATION_RATE,
IIF(TOURNAMENT_PHASE='Final', COUNT(DISTINCT IIF(CONCLUSION='WIN', TOURNAMENT_ID, NULL)), NULL) AS CHAMPION_COUNT,
IIF(TOURNAMENT_PHASE='Final', COUNT(DISTINCT IIF(CONCLUSION='LOSE', TOURNAMENT_ID, NULL)), NULL) AS RUNNERUP_COUNT,
COUNT(DISTINCT MATCH_ID) AS MATCHES_PLAYED,
COUNT(DISTINCT TOURNAMENT_ID) AS TOURNAMENTS_PLAYED,
COUNT(DISTINCT LOCATION_CITY) AS CITIES_PLAYED
FROM participant_match_results
LEFT JOIN (SELECT QUALIFICATION_CODE, PERSON_ID FROM persons) USING(PERSON_ID)
LEFT JOIN (SELECT QUALIFICATION_CODE, QUALIFICATION_SUCCESS FROM qualifications) USING(QUALIFICATION_CODE)
GROUP BY PERSON_ID, TOURNAMENT_PHASE
ORDER BY TOURNAMENT_PHASE, PARTICIPANT;
CREATE VIEW tournaments_view AS
SELECT
  TOURNAMENT_ID,
  TOURNAMENT_DATE,
  TOURNAMENT_STATE,
  ORGANISERS,
  POINT_SYSTEM_ID,
  TOURNAMENT_DURATION,
  LOCATION_NAME AS LOCATION,
  COUNT(DISTINCT PARTICIPANT_ID) AS NUMBER_OF_PARTICIPANTS,
  COUNT(DISTINCT MATCH_ID) AS NUMBER_OF_MATCHES,
  COUNT(DISTINCT MATCH_PLAYED) AS MATCHES_PLAYED,
  PARTICIPANT AS CHAMPION
FROM tournaments
LEFT JOIN tournament_states USING(TOURNAMENT_STATE_CODE)
LEFT JOIN participants USING(TOURNAMENT_ID)
-- Select Qualification matches only:
LEFT JOIN (SELECT DISTINCT MATCH_ID, TOURNAMENT_ID FROM matches WHERE TOURNAMENT_PHASE_CODE = 'Q') USING (TOURNAMENT_ID)
LEFT JOIN locations USING(LOCATION_CODE)
LEFT JOIN (SELECT TOURNAMENT_ID,PARTICIPANT FROM participant_match_results WHERE TOURNAMENT_PHASE = 'Final' AND CONCLUSION = 'WIN') USING(TOURNAMENT_ID)
LEFT JOIN (SELECT TOURNAMENT_ID, MATCH_ID AS MATCH_PLAYED FROM matches_view WHERE SCORE_1 IS NOT NULL AND SCORE_2 IS NOT NULL AND TOURNAMENT_PHASE = 'Qualification') USING(TOURNAMENT_ID)
LEFT JOIN (
  SELECT TOURNAMENT_ID,GROUP_CONCAT(PERSON_NAME, '; ') ORGANISERS FROM tournament_organisers
  LEFT JOIN persons USING(PERSON_ID)
  GROUP BY TOURNAMENT_ID
) USING (TOURNAMENT_ID)
GROUP BY TOURNAMENT_ID
ORDER BY TOURNAMENT_DATE;
CREATE VIEW table_statistics AS
SELECT *,
  IIF (SCORE_1=0 AND SCORE_2=0, 0.5,
    CAST(SCORE_1 AS FLOAT)/(CAST(SCORE_1 AS FLOAT) + CAST(SCORE_2 AS FLOAT))) AS SUCCESS_RATE,
  IIF (SCORE_U1=0 AND SCORE_U2=0, 0.5,
    CAST(SCORE_U1 AS FLOAT)/(CAST(SCORE_U1 AS FLOAT) + CAST(SCORE_U2 AS FLOAT))) AS SUCCESS_RATE_U
FROM (
  SELECT DISTINCT MATCH_ID, TOURNAMENT_ID, TOURNAMENT_PHASE, TABLE_NAME,
    MAX(CASE WHEN SIDE_DESCRIPTION = 'One' THEN RESULT ELSE NULL END) SCORE_1,
    MAX(CASE WHEN SIDE_DESCRIPTION = 'Two' THEN RESULT ELSE NULL END) SCORE_2,
    MAX(CASE WHEN SIDE_DESCRIPTION = 'Unknown side' THEN RESULT ELSE NULL END) SCORE_U1,
    MAX(CASE WHEN SIDE_DESCRIPTION = 'Unknown opposed side' THEN RESULT ELSE NULL END) SCORE_U2
  FROM (
    SELECT * FROM match_results
    LEFT JOIN matches USING(MATCH_ID)
    LEFT JOIN tournaments USING(TOURNAMENT_ID)
    LEFT JOIN tournament_phases USING(TOURNAMENT_PHASE_CODE)
    LEFT JOIN tables USING (TABLE_CODE)
    LEFT JOIN table_sides USING (SIDE_ID)
  ) GROUP BY MATCH_ID
);
CREATE VIEW table_summary AS
SELECT * FROM tables
LEFT JOIN (
  SELECT
    TABLE_NAME,
    SUM(SCORE_1) AS SCORED_SIDE_1,
    SUM(SCORE_2) AS SCORED_SIDE_2,
    SUM(SCORE_U1) AS SCORED_SIDE_U1,
    SUM(SCORE_U2) AS SCORED_SIDE_U2,
    AVG(SUCCESS_RATE) AS SUCCESS_RATE,
    COUNT(DISTINCT MATCH_ID) AS MATCHES_PLAYED,
    COUNT(DISTINCT TOURNAMENT_ID) AS TOURNAMENTS_PLAYED
  FROM table_statistics
  GROUP BY TABLE_NAME
) USING(TABLE_NAME);
CREATE VIEW picture_tag_names AS
